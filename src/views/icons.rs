/// Renders an inline `<svg>` that inherits `currentColor`.
pub fn icon(name: &str, class: &str) -> String {
    let filled = FILLED.contains(&name);
    format!(
        r#"<svg aria-hidden="true" focusable="false" class="icon{}" viewBox="0 0 24 24"{}><path d="{}"/></svg>"#,
        if filled { " icon--filled" } else { "" },
        if class.is_empty() {
            String::new()
        } else {
            format!(r#" data-class="{}""#, escape_html(class))
        },
        paths(name),
    )
}
